// cs2-codegen — generates C# types from schemas_jsonschema.json
//
// Usage:
//   dotnet run -- <path-to-schemas_jsonschema.json> [output-directory]
//
// Each $defs entry with x-cs2-kind "class" or "enum" is emitted as a C# type.
// Synthetic math types (Vector, QAngle, Color, …) are emitted as readonly structs.
// Types are grouped by x-cs2-module into one .cs file per module.
// Inheritance is expressed via allOf+$ref → "class Foo : Bar".
// Flags enums get [Flags] based on x-cs2-flags: true.
// Nullable fields come from oneOf:[T, null] → T?.

using System.Text;
using System.Text.Json;

if (args.Length == 0)
{
    Console.Error.WriteLine("Usage: cs2-codegen <schemas_jsonschema.json> [output-dir]");
    return 1;
}

var schemaPath = args[0];
var outputDir  = args.Length > 1 ? args[1] : "cs2-types";

if (!File.Exists(schemaPath))
{
    Console.Error.WriteLine($"File not found: {schemaPath}");
    return 1;
}

Directory.CreateDirectory(outputDir);

using var stream = File.OpenRead(schemaPath);
using var doc    = JsonDocument.Parse(stream);
var root = doc.RootElement;

var revision  = root.TryGetProperty("x-cs2-revision",    out var rev) ? rev.ToString()        : "unknown";
var verDate   = root.TryGetProperty("x-cs2-version-date", out var vd) ? vd.GetString()         : "";
var generator = root.TryGetProperty("x-cs2-generator",    out var gen) ? gen.GetString()        : "";
var fileHeader = $"// Auto-generated by cs2-codegen from {Path.GetFileName(schemaPath)}\n" +
                 $"// Revision {revision} ({verDate}) — {generator}\n" +
                 $"// Do not edit by hand.";

// Collect entries by module. Synthetics go in a dedicated "synthetics" module.
var defs    = root.GetProperty("$defs");
var byModule = new SortedDictionary<string, List<(string name, string kind, JsonElement def)>>();

foreach (var prop in defs.EnumerateObject())
{
    var d = prop.Value;
    if (d.TryGetProperty("x-cs2-forward-declared", out var fwd) && fwd.GetBoolean())
    {
        // Forward-declared types exist only in tool modules that weren't loaded at dump time.
        // Emit an empty stub so the generated assembly compiles.
        AddEntry("stubs", prop.Name, "stub", d);
        continue;
    }

    if (d.TryGetProperty("x-cs2-synthetic", out var syn) && syn.GetBoolean())
    {
        // Emit synthetic math types as readonly structs in their own file
        var syntKind = d.TryGetProperty("type", out var t) && t.GetString() == "array"
            ? "synthetic-array"
            : "synthetic-object";
        AddEntry("synthetics", prop.Name, syntKind, d);
        continue;
    }

    if (!d.TryGetProperty("x-cs2-kind", out var kindEl)) continue;
    var module = d.TryGetProperty("x-cs2-module", out var modEl)
        ? modEl.GetString() ?? "global"
        : "global";
    AddEntry(module, prop.Name, kindEl.GetString()!, d);
}

void AddEntry(string module, string name, string kind, JsonElement def)
{
    if (!byModule.TryGetValue(module, out var list))
        byModule[module] = list = [];
    list.Add((name, kind, def));
}

// Emit one .cs file per module. All types share a single namespace so cross-module
// $refs resolve without additional using directives.
int totalTypes = 0;
foreach (var (module, entries) in byModule)
{
    var sb = new StringBuilder();
    sb.AppendLine(fileHeader);
    sb.AppendLine($"// Module: {module}");
    sb.AppendLine();
    sb.AppendLine("#nullable enable");
    sb.AppendLine("#pragma warning disable CS8618  // non-nullable property not initialized (expected in generated serialization types)");
    sb.AppendLine();
    sb.AppendLine("using System;");
    sb.AppendLine("using System.Collections.Generic;");
    sb.AppendLine("using System.Text.Json.Serialization;");
    sb.AppendLine();
    sb.AppendLine("namespace CS2Schema;");
    sb.AppendLine();

    foreach (var (name, kind, def) in entries.OrderBy(e => e.name))
    {
        switch (kind)
        {
            case "class":            EmitClass          (sb, name, def); break;
            case "enum":             EmitEnum           (sb, name, def); break;
            case "synthetic-object": EmitSyntheticStruct(sb, name, def); break;
            case "synthetic-array":  EmitArrayStruct    (sb, name, def); break;
            case "stub":             EmitStub           (sb, name);      break;
        }
    }

    var outPath = Path.Combine(outputDir, SanitizeFilename(module) + ".cs");
    File.WriteAllText(outPath, sb.ToString(), Encoding.UTF8);
    Console.WriteLine($"  {outPath}  ({entries.Count} types)");
    totalTypes += entries.Count;
}

Console.WriteLine($"Done — {totalTypes} types across {byModule.Count} modules.");
return 0;

// ─── Class emitter ─────────────────────────────────────────────────────────

void EmitClass(StringBuilder sb, string name, JsonElement def)
{
    var size = def.TryGetProperty("x-cs2-size", out var sz) ? $", {sz.GetInt32()} bytes" : "";
    sb.AppendLine($"/// <summary>{name}{size}</summary>");

    string? baseClass = null;
    var extraParents  = new List<string>();
    if (def.TryGetProperty("allOf", out var allOf))
    {
        foreach (var item in allOf.EnumerateArray())
        {
            if (item.TryGetProperty("$ref", out var r))
            {
                var pname = Esc(RefToName(r.GetString()!));
                if (baseClass is null) baseClass = pname;
                else                  extraParents.Add(pname);
            }
        }
    }

    var inherit = baseClass is not null ? $" : {baseClass}" : "";
    sb.AppendLine($"public class {Esc(SanitizeName(name))}{inherit}");
    sb.AppendLine("{");

    if (extraParents.Count > 0)
        sb.AppendLine($"    // NOTE: additional parents (C# single-inheritance): {string.Join(", ", extraParents)}");

    if (def.TryGetProperty("properties", out var props))
    {
        foreach (var prop in props.EnumerateObject())
        {
            var jsonName = prop.Name;
            var csType   = MapType(prop.Value);
            var offset   = prop.Value.TryGetProperty("x-cs2-offset", out var off)
                ? $"  // +0x{off.GetInt32():X}"
                : "";

            sb.AppendLine($"    [JsonPropertyName(\"{jsonName}\")]");
            sb.AppendLine($"    public {csType} {FieldToPropName(jsonName)} {{ get; set; }}{offset}");
        }
    }

    sb.AppendLine("}");
    sb.AppendLine();
}

// ─── Enum emitter ──────────────────────────────────────────────────────────

void EmitEnum(StringBuilder sb, string name, JsonElement def)
{
    var isFlags    = def.TryGetProperty("x-cs2-flags", out var fl) && fl.GetBoolean();
    var fmt        = def.TryGetProperty("format", out var f) ? f.GetString() : null;
    var underlying = fmt switch {
        "uint8"  => " : byte",   "uint16" => " : ushort",
        "uint32" => " : uint",   "uint64" => " : ulong",
        "int8"   => " : sbyte",  "int16"  => " : short",
        "int32"  => " : int",    "int64"  => " : long",
        _ => ""
    };
    var isUnsigned = fmt is "uint8" or "uint16" or "uint32" or "uint64";

    if (isFlags) sb.AppendLine("[Flags]");
    sb.AppendLine($"public enum {Esc(SanitizeName(name))}{underlying}");
    sb.AppendLine("{");

    foreach (var (memberName, value) in ReadEnumMembers(def))
    {
        // C++ uses -1 as a sentinel in unsigned enums (e.g. INVALID = ~0u).
        // Reinterpret to the correct unsigned bit pattern so C# accepts it.
        var valueStr = (isUnsigned && value < 0)
            ? ReinterpretUnsigned(value, fmt!).ToString()
            : value.ToString();
        sb.AppendLine($"    {Esc(memberName)} = {valueStr},");
    }

    sb.AppendLine("}");
    sb.AppendLine();
}

// ─── Synthetic type emitters ────────────────────────────────────────────────

// Object synthetics (Vector, QAngle, Color, …) → readonly struct with float fields
void EmitSyntheticStruct(StringBuilder sb, string name, JsonElement def)
{
    var desc = def.TryGetProperty("description", out var d) ? d.GetString() ?? name : name;
    sb.AppendLine($"/// <summary>{desc}</summary>");
    sb.AppendLine($"public readonly struct {Esc(SanitizeName(name))}");
    sb.AppendLine("{");

    if (def.TryGetProperty("properties", out var props))
    {
        foreach (var prop in props.EnumerateObject())
        {
            var csType = MapType(prop.Value);
            sb.AppendLine($"    [JsonPropertyName(\"{prop.Name}\")]");
            sb.AppendLine($"    public {csType} {FieldToPropName(prop.Name)} {{ get; init; }}");
        }
    }

    sb.AppendLine("}");
    sb.AppendLine();
}

// Array synthetics (matrix3x4_t, fltx4, …) → readonly struct wrapping a fixed-size array
void EmitArrayStruct(StringBuilder sb, string name, JsonElement def)
{
    var desc      = def.TryGetProperty("description", out var d) ? d.GetString() ?? name : name;
    var itemType  = def.TryGetProperty("items", out var items) ? MapType(items) : "float";
    var minItems  = def.TryGetProperty("minItems", out var mi) ? mi.GetInt32() : 0;

    sb.AppendLine($"/// <summary>{desc}</summary>");
    sb.AppendLine($"public readonly struct {Esc(SanitizeName(name))}");
    sb.AppendLine("{");
    sb.AppendLine($"    [JsonPropertyName(\"values\")]");
    sb.AppendLine($"    public {itemType}[] Values {{ get; init; }}  // {minItems} elements");
    sb.AppendLine("}");
    sb.AppendLine();
}

// Forward-declared type that wasn't available at dump time — empty placeholder
void EmitStub(StringBuilder sb, string name)
{
    sb.AppendLine($"/// <summary>{name} — forward-declared stub (type was not loaded at dump time)</summary>");
    sb.AppendLine($"public class {Esc(SanitizeName(name))} {{ }}");
    sb.AppendLine();
}

// ─── Type mapper ───────────────────────────────────────────────────────────

string MapType(JsonElement schema)
{
    if (schema.TryGetProperty("x-cs2-unresolved", out var unres) && unres.GetBoolean())
        return "object /* opaque */";

    // Nullable: oneOf [T, {type:null}] → T?
    if (schema.TryGetProperty("oneOf", out var oneOf))
    {
        var nonNull = new List<JsonElement>();
        foreach (var s in oneOf.EnumerateArray())
        {
            if (s.ValueKind == JsonValueKind.Null) continue;
            if (s.ValueKind == JsonValueKind.Object &&
                s.TryGetProperty("type", out var tEl) && tEl.GetString() == "null") continue;
            nonNull.Add(s);
        }
        return nonNull.Count == 1 ? MapType(nonNull[0]) + "?" : "object /* union */";
    }

    if (schema.TryGetProperty("$ref", out var refEl))
        return Esc(RefToName(refEl.GetString()!));

    if (schema.TryGetProperty("type", out var typeEl) && typeEl.GetString() == "array")
    {
        if (schema.TryGetProperty("items", out var items))
            return MapType(items) + "[]";
        return "object[]";
    }

    var typeName = schema.TryGetProperty("type", out var tn)  ? tn.GetString()     : null;
    var format   = schema.TryGetProperty("format", out var fm) ? fm.GetString()     : null;

    return (typeName, format) switch {
        ("boolean", _)        => "bool",
        ("integer", "int8")   => "sbyte",   ("integer", "int16")  => "short",
        ("integer", "int32")  => "int",      ("integer", "int64")  => "long",
        ("integer", "uint8")  => "byte",     ("integer", "uint16") => "ushort",
        ("integer", "uint32") => "uint",     ("integer", "uint64") => "ulong",
        ("integer", _)        => "int",
        ("number",  "double") => "double",   ("number",  _)        => "float",
        ("string",  "uuid")   => "Guid",     ("string",  _)        => "string",
        ("object",  _)        => "Dictionary<string, object> /* map */",
        _ => "object"
    };
}

// ─── Enum member reader ────────────────────────────────────────────────────

IEnumerable<(string name, long value)> ReadEnumMembers(JsonElement def)
{
    // New format: anyOf:[{const:N, title:"NAME"}, ...]
    if (def.TryGetProperty("anyOf", out var anyOf))
    {
        foreach (var entry in anyOf.EnumerateArray())
            if (entry.TryGetProperty("const", out var c) && entry.TryGetProperty("title", out var t))
                yield return (t.GetString()!, c.GetInt64());
        yield break;
    }
    // Legacy format: x-cs2-enum-values:{NAME: value, ...}
    if (def.TryGetProperty("x-cs2-enum-values", out var vals))
        foreach (var kv in vals.EnumerateObject())
            yield return (kv.Name, kv.Value.GetInt64());
}

// ─── Helpers ───────────────────────────────────────────────────────────────

// "#/$defs/Foo::Bar" → "Foo_Bar"
static string RefToName(string refStr)
{
    const string prefix = "#/$defs/";
    var name = refStr.StartsWith(prefix, StringComparison.Ordinal)
        ? refStr[prefix.Length..]
        : refStr;
    return SanitizeName(name);
}

// C++ nested-class "::" → "_" (only non-identifier chars seen in Valve schemas)
static string SanitizeName(string name) => name.Replace("::", "_");

// "m_flRadius" → "M_flRadius"
static string FieldToPropName(string s) =>
    string.IsNullOrEmpty(s) ? "_" : char.ToUpperInvariant(s[0]) + s[1..];

static string SanitizeFilename(string s) =>
    string.Concat(s.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_'));

// Reinterpret a negative int64 value as its unsigned counterpart for the given format.
// Used for sentinel values like INVALID = ~0u in C++ that arrive as -1 in int64 storage.
static ulong ReinterpretUnsigned(long value, string fmt) => fmt switch {
    "uint8"  => (byte  )(sbyte )(int)value,
    "uint16" => (ushort)(short )(int)value,
    "uint32" => (uint  )       (int)value,
    "uint64" => (ulong)             value,
    _ => (ulong)value
};

// Escape C# reserved keywords with @
static string Esc(string id) => id switch {
    "class"    or "event"     or "interface"  or "namespace" or "object"   or
    "string"   or "new"       or "base"       or "this"      or "void"     or
    "bool"     or "int"       or "long"       or "float"     or "double"   or
    "byte"     or "short"     or "uint"       or "ulong"     or "ushort"   or
    "sbyte"    or "char"      or "decimal"    or "delegate"  or "enum"     or
    "fixed"    or "goto"      or "in"         or "is"        or "lock"     or
    "operator" or "out"       or "override"   or "params"    or "readonly" or
    "ref"      or "sealed"    or "sizeof"     or "static"    or "struct"   or
    "throw"    or "try"       or "typeof"     or "unsafe"    or "using"    or
    "virtual"  or "volatile"  or "checked"    or "unchecked"
        => "@" + id,
    _ => id
};
